export async function isDeployed(conn: Connection) {
  const info = await conn.getAccountInfo(PROGRAM_ID).catch(() => null);
  return !!info?.executable;
}

const variant = (e: object) => Object.keys(e)[0];
const hex = (b: number[]) => b.map((x) => x.toString(16).padStart(2, '0')).join('');

// --- Change records from transaction history ----------------------------------

const parser = new EventParser(PROGRAM_ID, program.coder);
const ixCoder = program.coder.instruction as BorshInstructionCoder;
/** What one transaction contributes: timeline actions, and the proposals it executed or vetoed. */
interface Mapped {
  actions: Action[];
  proposals: { id: number; tx: string }[];
}

// Confirmed transactions never change, so each is fetched and mapped once.
// ponytail: one entry per signature for the server instance's lifetime; fine at demo scale.
const seen = new Map<string, Mapped>();

/** Fast-lane, guardian, reserve and setup actions, and refused fast-lane attempts, read from chain. */
async function history(conn: Connection, addresses: PublicKey[], decimals: number): Promise<Mapped> {
  // ponytail: newest 1000 signatures per address; page with `before` if a config outgrows that.
  const lists = [];
  for (const a of addresses) lists.push(await withRetry(() => conn.getSignaturesForAddress(a, { limit: 1000 })));
  const sigs = [...new Set(lists.flat().map((s) => s.signature))];
  // One request at a time: the public devnet RPC answers batched getTransactions
  // with 429. A transaction that still can't be fetched is skipped and retried on
  // the next refresh, so a rate limit thins the history instead of hiding it.
  for (const sig of sigs.filter((s) => !seen.has(s))) {
    const tx = await withRetry(() =>
      conn.getTransaction(sig, { maxSupportedTransactionVersion: 0, commitment: 'confirmed' }),
    ).catch(() => null);
    if (tx) seen.set(sig, actionsOf(tx, sig, decimals));
  }
  const mapped = sigs.map((s) => seen.get(s)).filter((m) => !!m);
  return { actions: mapped.flatMap((m) => m.actions), proposals: mapped.flatMap((m) => m.proposals) };
}

/** Retries rate-limited RPC calls with backoff (0.5s, 1s, 2s, 4s). */
async function withRetry<T>(call: () => Promise<T>): Promise<T> {
  for (let attempt = 0; ; attempt++) {
    try {
      return await call();
    } catch (e) {
      const limited = /429|Too many requests/i.test(String((e as Error)?.message ?? e));
      if (!limited || attempt >= 3) throw e;
      await new Promise((r) => setTimeout(r, 500 * 2 ** attempt));
    }
  }
}

/** Vetowall's top-level instructions in a transaction, decoded with the IDL. */
function vetowallIxs(tx: VersionedTransactionResponse) {
  const msg = tx.transaction.message;
  const keys = msg.getAccountKeys({ accountKeysFromLookups: tx.meta?.loadedAddresses });
  return msg.compiledInstructions
    .filter((ix) => keys.get(ix.programIdIndex)?.equals(PROGRAM_ID))
    .map((ix) => ({
      decoded: ixCoder.decode(Buffer.from(ix.data)),
      keys: ix.accountKeyIndexes.map((k) => keys.get(k)!.toBase58()),
    }));
}

function actionsOf(tx: VersionedTransactionResponse, sig: string, decimals: number): Mapped {
  const logs = tx.meta?.logMessages ?? [];
  const ixs = vetowallIxs(tx);
  if (tx.meta?.err) {
    // Failed transactions emit nothing; a refused fast-lane attempt is still evidence.
    const now = ixs.find((i) => i.decoded?.name === 'executeNow');
    if (!now) return { actions: [], proposals: [] };
    const [, proposer, approver] = now.keys;
    const args = now.decoded!.data as Routed & { targetProgram: PublicKey };
    return {
      actions: [refusedAction(args, { proposer, approver: approver === PROGRAM_ID.toBase58() ? undefined : approver },
        errorName(logs), tx.blockTime ?? 0, sig, decimals)],
      proposals: [],
    };
  }
  // Routed records pair, in order, with the routed instructions that produced them.
  const routed = ixs
    .filter((i) => i.decoded?.name === 'executeNow' || i.decoded?.name === 'guardianExecute')
    .map((i) => i.decoded!.data as Routed);
  const out: Action[] = [];
  const proposals: Mapped['proposals'] = [];
  for (const e of parser.parseLogs(logs)) {
    if (e.name !== 'changeRecord') continue;
    const r = e.data as DecodedRecord;
    const k = Object.keys(r.kind)[0];
    // The transaction that executed or vetoed a proposal is its closing evidence.
    if ((k === 'executed' || k === 'vetoed') && r.proposalId !== null) proposals.push({ id: Number(r.proposalId.toString()), tx: sig });
    const a = recordToAction(r, sig, decimals, k === 'executedNow' || k === 'guardianExecuted' ? routed.shift() : undefined);
    if (a) out.push({ ...a, seq: out.length });
  }
  return { actions: out, proposals };
}

/**
 * Reads a live deployment. Without a mint, uses the mint of the config's
 * first Reserve. Returns null if the config doesn't exist.
 */
export async function loadSnapshot(conn: Connection, config: PublicKey, mintHint?: PublicKey): Promise<Snapshot | null> {
  const accounts = accountsOn(conn);
  const cfg = await accounts.config.fetchNullable(config);
  if (!cfg) return null;
  const mint: PublicKey | undefined =
    mintHint ?? (await accounts.reserve.all([{ memcmp: { offset: 8, bytes: config.toBase58() } }]))[0]?.account.mint;
  if (!mint) return null;
  const reservePda = pda.reserve(config, mint);
  const [proposals, m, reserve, policy] = await Promise.all([
    accounts.proposal.all([{ memcmp: { offset: 8, bytes: config.toBase58() } }]),
    readMint(conn, mint),
    accounts.reserve.fetchNullable(reservePda),
    accounts.policy.fetchNullable(pda.policy(config, TOKEN_2022, discOf(Uint8Array.of(7)))),
  ]);
  const unit = 10 ** m.decimals;
  const proposer = cfg.proposer.toBase58();
  const approver = cfg.approver?.toBase58();
  const actions: Action[] = proposals.map(({ publicKey, account: p }) => {
    const status = variant(p.status) as Action['status'];
    const cls = CLASSES.find((c) => c.toLowerCase() === variant(p.class).toLowerCase()) ?? 'Max';
    return {
      id: Number(p.id),
      address: publicKey.toBase58(),
      path: 'timelock',
      ...describe(p.targetProgram.toBase58(), Uint8Array.from(p.data), p.accounts, m.decimals),
      class: cls,
      status,
      queuedAt: Number(p.queuedAt),
      eta: Number(p.eta),
      executedAt: Number(p.executedAt) || undefined,
      maker: proposer,
      checker: approver,
      vetoReason: status === 'vetoed' ? hex(p.vetoReason) : undefined,
    };
  });
  // attest_reserve doesn't take the config, so its records are found via the Reserve.
  // History is best-effort: live account state still renders if the RPC refuses it.
  const past = await history(conn, [config, reservePda], m.decimals).catch(() => ({ actions: [], proposals: [] }) as Mapped);
  for (const { id, tx } of past.proposals) {
    const a = actions.find((x) => x.id === id);
    if (a) a.tx = tx;
  }
  actions.push(...past.actions);
  const now = Date.now() / 1000;
  const limit = policy?.limit;
  return {
    source: 'live',
    deployment: {
      config: config.toBase58(),
      authority: pda.authority(config).toBase58(),
      mint: mint.toBase58(),
      symbol: m.symbol,
      decimals: m.decimals,
      proposer,
      approver,
      guardian: cfg.guardian.toBase58(),
      attestor: reserve?.attestor.toBase58(),
      delays: cfg.delays.map(Number) as Snapshot['deployment']['delays'],
    },
    actions,
    supply: Number(m.supply) / unit,
    reserve: reserve
      ? { amount: Number(reserve.amount) / unit, updatedAt: Number(reserve.updatedAt), maxAge: Number(reserve.maxAge) }
      : null,
    cap: limit
      ? {
          cap: Number(limit.cap) / unit,
          // The program resets `used` lazily when a new window starts.
          used: now > Number(policy.windowStart) + Number(limit.window) ? 0 : Number(policy.used) / unit,
          windowStart: Number(policy.windowStart),
          window: Number(limit.window),
        }
      : null,
    authorities: m.authorities,
    paused: m.paused,
  };
}
